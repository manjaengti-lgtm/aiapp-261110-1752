def o(id, name, roles, level, email=None, phone=None, other=None, fax=None, address=None, url=None, note=None, default=True, src=None):
    d = {"id": id, "name": name, "roles": roles, "level": level}
    for k, v in [("email", email), ("phone", phone), ("otherPhones", other), ("fax", fax),
                 ("address", address), ("url", url), ("note", note), ("source", src)]:
        if v: d[k] = v
    if not default: d["defaultSelected"] = False
    return d

